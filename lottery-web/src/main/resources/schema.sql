CREATE TABLE IF NOT EXISTS draws (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game VARCHAR(2) NOT NULL CHECK (game IN ('PB','MM')),
  draw_date DATE NOT NULL,
  w1 INT NOT NULL, w2 INT NOT NULL, w3 INT NOT NULL, w4 INT NOT NULL, w5 INT NOT NULL,
  special INT,
  source VARCHAR(255) NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT unique_game_date UNIQUE (game, draw_date),
  CONSTRAINT sorted_whites CHECK (w1 > 0 AND w1 < w2 AND w2 < w3 AND w3 < w4 AND w4 < w5 AND w5 <= 75),
  CONSTRAINT positive_special CHECK (special IS NULL OR special BETWEEN 1 AND 99)
);
CREATE TABLE IF NOT EXISTS imports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game VARCHAR(2) NOT NULL, source VARCHAR(255) NOT NULL,
  added INT NOT NULL, corrected INT NOT NULL, unchanged INT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS draw_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game VARCHAR(2) NOT NULL, draw_date DATE NOT NULL,
  previous_values VARCHAR(100) NOT NULL, new_values VARCHAR(100) NOT NULL,
  source VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
